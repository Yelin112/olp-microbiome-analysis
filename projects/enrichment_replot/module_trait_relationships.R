module_colors <- c(
  MEblue = "#4D94FF",
  MEbrown = "#8B5A2B",
  MEpink = "#FF69B4",
  MEyellow = "#FFD700",
  MEgreen = "#00C000",
  MEturquoise = "#00CED1",
  MEblack = "#333333",
  MEmagenta = "#CC00CC",
  MEred = "#EE2222",
  MEgrey = "#999999"
)

df_plot <- module_trait_df[module_trait_df$species %in% selected_species, ]

# Preserve original left-to-right species order
df_plot$species <- factor(df_plot$species, levels = selected_species)

# Modules: top-to-bottom (MEblue on top → reverse for ggplot y-axis)
module_levels <- c(
  "MEblue",
  "MEbrown",
  "MEpink",
  "MEyellow",
  "MEgreen",
  "MEturquoise",
  "MEblack",
  "MEmagenta",
  "MEred",
  "MEgrey"
)
df_plot$module <- factor(df_plot$module, levels = rev(module_levels))

# Significance label: use · for near-significant trend (optional, kept clean)
df_plot$sig_label <- ifelse(
  df_plot$p_value < 0.001,
  "***",
  ifelse(df_plot$p_value < 0.01, "**", ifelse(df_plot$p_value < 0.05, "*", ""))
)

# Clamp r for color scale
r_limit <- max(abs(df_plot$r), na.rm = TRUE)
r_limit <- ceiling(r_limit * 10) / 10 # round up to nearest 0.1

p_heatmap <- ggplot(df_plot, aes(x = species, y = module, fill = r)) +
  geom_tile(color = "white", linewidth = 0.5) +
  coord_fixed(ratio = 1)+
  geom_text(
    aes(label = sig_label),
    size = 4,
    vjust = 0.5,
    color = "black"
  ) +
  scale_fill_gradient2(
    low = "#2166AC",
    mid = "white",
    high = "#B2182B",
    midpoint = 0,
    limits = c(-r_limit, r_limit),
    name = "Correlation"
  ) +
  scale_x_discrete(position = "bottom") +
  scale_y_discrete(
    labels = function(x) gsub("^ME", "ME", x)
  ) +
  labs(
    title = "Module–trait relationships",
    x = NULL,
    y = NULL,
    caption = "* p < 0.05  ** p < 0.01  *** p < 0.001"
  ) +
  theme_minimal(base_size = 11) +
  theme(
    plot.title = element_text(hjust = 0.5, face = "bold", size = 13),
    axis.text.x = element_text(
      angle = 45,
      hjust = 1,
      vjust = 1,
      size = 9,
      face = "italic"
    ),
    axis.text.y = element_text(
      size = 10,
      face = "bold",
      color = rev(module_colors[module_levels])
    ),
    panel.grid = element_blank(),
