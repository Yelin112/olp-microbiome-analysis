#' 从单次测量值生成伪重复（噪声注入）
#'
#' @description
#' \strong{安全警告}：本函数生成的是人为合成的伪重复值，不是真实的独立重复。
#' 仅用于探索性可视化/占位，严禁直接用于假设检验或论文正式统计结论。
#' 每次调用都会打印 warning，返回值带 \code{attr(x, "synthetic") == TRUE} 标记。
#'
#' @param x 单个数值、数值向量，或 data.frame。
#' @param type 数据类型标签，必须显式指定（不做自动推断）：
#'   \code{"continuous"} / \code{"proportion"} / \code{"abundance"} / \code{"count"}。
#' @param n 每个数据点生成的重复数，默认 3。
#' @param cv 变异系数，用于 continuous/proportion/abundance，默认 0.05。
#' @param dispersion 负二项离散参数（size），用于 count，默认 3。
#' @param clip 有界数据（abundance）是否裁剪到合法范围 [0,1]，默认 TRUE。
#' @param seed 随机种子。传入时结果可重复，且不会污染全局随机状态
#'   （函数退出后自动恢复调用前的 \code{.Random.seed}）。
#' @param col data.frame 模式下的目标列名（字符串）。
#' @param scale proportion 类型专用：\code{"auto"}（默认，沿用 value > 1 时按
#'   百分比处理的启发式，遇到时会 warning 提示这个启发式的局限）/
#'   \code{"0-1"} / \code{"0-100"}——显式指定可避免 0~1 与 0~100 两种格式在
#'   数值 <= 1 时无法区分的问题。
#'
#' @return
#'   - 单值输入 → 长度为 n 的数值向量
#'   - 向量输入 → 矩阵（行 = 原始数据点，列 = 重复），\code{n = 1} 时也返回矩阵（1 列），保持类型稳定
#'   - data.frame 输入 → 原数据框新增 \code{col_rep1...col_repN} 列
#'
#'   返回值均带 \code{synthetic} / \code{synthetic_type} / \code{synthetic_warning} attribute。
#'
#' @examples
#' generate_replicates(0.75, type = "proportion", n = 3, seed = 1)
#' generate_replicates(c(0.12, 0.08, 0.15), type = "abundance", n = 3, seed = 1)
generate_replicates <- function(
    x,
    type,
    n          = 3,
    cv         = 0.05,
    dispersion = 3,
    clip       = TRUE,
    seed       = NULL,
    col        = NULL,
    scale      = c("auto", "0-1", "0-100")
) {
  type  <- match.arg(type, c("continuous", "proportion", "abundance", "count"))
  scale <- match.arg(scale)

  if (!is.numeric(n) || length(n) != 1 || is.na(n) || n < 1 || n != round(n)) {
    stop("n 必须是 >= 1 的整数")
  }
  n <- as.integer(n)
  if (!is.numeric(cv) || cv <= 0) stop("cv 必须是正数")
  if (!is.numeric(dispersion) || dispersion <= 0) stop("dispersion 必须是正数")

  # ---- RNG 隔离：不污染调用者的全局随机状态 ----
  if (!is.null(seed)) {
    if (!exists(".Random.seed", envir = .GlobalEnv)) stats::runif(1)
    old_seed <- get(".Random.seed", envir = .GlobalEnv)
    on.exit(assign(".Random.seed", old_seed, envir = .GlobalEnv), add = TRUE)
    set.seed(seed)
  }

  generator <- switch(type,
    continuous = function(v) .grf_continuous(v, n, cv),
    proportion = function(v) .grf_proportion(v, n, cv, scale),
    abundance  = function(v) .grf_abundance(v, n, cv, clip),
    count      = function(v) .grf_count(v, n, dispersion)
  )

  # ---- data.frame 模式 ----
  if (is.data.frame(x)) {
    if (is.null(col)) stop("x 是 data.frame 时必须指定 col 参数")
    if (!col %in% names(x)) stop("列 '", col, "' 不存在于 data.frame 中")
    values <- x[[col]]
    if (!is.numeric(values)) stop("列 '", col, "' 必须是数值列")

    reps <- do.call(rbind, lapply(values, generator))
    colnames(reps) <- paste0(col, "_rep", seq_len(n))
    out <- cbind(x, as.data.frame(reps))
    return(.grf_tag_synthetic(out, type))
  }

  # ---- 数值输入 ----
  if (!is.numeric(x)) stop("x 必须是数值、数值向量或 data.frame")

  if (length(x) == 1) {
    result <- generator(x)
    return(.grf_tag_synthetic(result, type))
  }

  # 向量输入 -> 矩阵（行 = 数据点，列 = 重复），n=1 时也保持矩阵，类型稳定
  # 用 lapply + rbind 而不是 vapply(x, generator, numeric(n))：
  # vapply 在 n == 1 时会把结果 simplify 成向量，丢失矩阵结构。
  reps <- do.call(rbind, lapply(x, generator))
  colnames(reps) <- paste0("rep", seq_len(n))
  rownames(reps) <- NULL
  .grf_tag_synthetic(reps, type)
}
