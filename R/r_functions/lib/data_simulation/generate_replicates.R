# generate_replicates — 从单次测量值生成伪重复（噪声注入）
# 版本: 0.1 (dev)
# 依赖: stats（base R 自带）
# ============================================================================
#
# !! 安全警告 / SAFETY NOTICE !!
# 本函数生成的是「人为合成」的伪重复值，不是真实的独立生物学/技术重复。
# 仅用于探索性可视化、占位图、demo。
# 严禁直接用这些伪重复跑假设检验（t 检验/ANOVA 等）或将结果写入正式论文的
# 统计结论——那是编造数据。每次调用都会打印 warning，并在返回值上打标记
# (attr(x, "synthetic") == TRUE) 供下游代码/审查识别。
#
# 用法: source("R/r_functions/lib/data_simulation/generate_replicates.R")

# ============================================================================
# 0. 内部工具：安全阀（每次调用都打标记 + 警告）
# ============================================================================

.grf_tag_synthetic <- function(x, type) {
  warning(
    "generate_replicates(): 返回值是由单次观测值人为生成的伪重复（noise-injected），",
    "不是真实的独立生物学/技术重复，仅供探索性可视化/占位使用。",
    "不得直接用于假设检验（t 检验等）或作为论文正式统计结论的依据。 [type = ", type, "]",
    call. = FALSE
  )
  attr(x, "synthetic") <- TRUE
  attr(x, "synthetic_type") <- type
  attr(x, "synthetic_warning") <- paste0(
    "generated by generate_replicates() [type = ", type, "] - ",
    "not real replicates, do not use for hypothesis testing"
  )
  x
}

# ============================================================================
# 1. 各类型噪声策略（内部函数，均接受单个标量 value，返回长度 n 的 numeric）
# ============================================================================

.grf_continuous <- function(value, n, cv) {
  if (is.na(value)) return(rep(NA_real_, n))
  if (value == 0) {
    warning("continuous: 值为 0，SD 也为 0，返回 n 个 0", call. = FALSE)
    return(rep(0, n))
  }
  if (value < 0) {
    warning("continuous: 传入负值，SD 用 |value| 计算", call. = FALSE)
  }
  sd <- abs(value) * cv
  stats::rnorm(n, mean = value, sd = sd)
}

.grf_proportion <- function(value, n, cv, scale = "auto") {
  if (is.na(value)) return(rep(NA_real_, n))

  is_pct_input <- switch(scale,
    "0-1"   = FALSE,
    "0-100" = TRUE,
    "auto"  = value > 1
  )
  if (scale == "auto" && value > 1) {
    warning(
      "proportion: 值 > 1，自动按 0~100 格式处理（除以 100）。",
      "注意：0~1 和 0~100 两种格式在数值 <= 1 时无法从数值本身区分",
      "（例如 0.5 既可能是比例 50%，也可能是百分比 0.5%）。",
      "如果你的数据本身可能是很小的百分比（如抑制率 0.5%），",
      "请显式传入 scale = \"0-100\" 避免误判。",
      call. = FALSE
    )
  }

  value_01 <- if (is_pct_input) value / 100 else value
  if (value_01 <= 0 || value_01 >= 1) {
    stop(
      "proportion: 值为 0 或 1（100%）时 logit 无法计算（结果为 ±Inf）。value = ",
      value, call. = FALSE
    )
  }

  logit_val <- log(value_01 / (1 - value_01))
  logit_sd  <- cv * abs(logit_val) + 0.05
  logit_rep <- stats::rnorm(n, mean = logit_val, sd = logit_sd)
  result_01 <- stats::plogis(logit_rep)

  if (is_pct_input) result_01 * 100 else result_01
}

.grf_abundance <- function(value, n, cv, clip = TRUE) {
  if (is.na(value)) return(rep(NA_real_, n))
  if (value < 0) {
    stop("abundance: 值必须 >= 0，传入了 ", value, call. = FALSE)
  }
  if (value == 0) {
    warning("abundance: 值为 0，返回 n 个 0", call. = FALSE)
    return(rep(0, n))
  }

  log_val <- log1p(value)
  log_sd  <- cv * abs(log_val) + 0.01
  log_rep <- stats::rnorm(n, mean = log_val, sd = log_sd)
  result  <- expm1(log_rep)

  if (clip) {
    result <- pmin(pmax(result, 0), 1)
  } else if (any(result < 0 | result > 1)) {
    warning("abundance: 生成值超出 [0,1] 合法范围（clip=FALSE，未裁剪）", call. = FALSE)
  }
  result
}

.grf_count <- function(value, n, dispersion) {
  if (is.na(value)) return(rep(NA_real_, n))
  if (value < 0) {
    stop("count: 值必须 >= 0，传入了 ", value, call. = FALSE)
  }
  if (value == 0) {
    return(rep(0, n))
  }
  # 注意：rnbinom() 的 mu 参数不要求整数，这里不强制 round() 原始值，
  # 避免丢失精度（这一点与交接文档的原始设计不同，见 notes.md）。
  as.double(stats::rnbinom(n, mu = value, size = dispersion))
}

